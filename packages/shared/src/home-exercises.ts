/**
 * "Use what you have" exercises. DRAFTS: original, plainly worded exercises that use only ordinary household items in the ways listed in home-items.ts. No exercise
 * professional has reviewed them, so each carries a `draft` marker, they are never bundled or seeded, and they appear only in development and review builds. The
 * rules they follow (checked by tests) are: nothing is stood on, nothing is anchored, the chair is only sat on or held for light support, bottles and backpacks are
 * only light loads held in the hands or at the chest, the stairs exercises use only the bottom step beside a handrail and never carry a load, and every exercise has
 * an easier version and a stop-if note. No weight is stated except "a standard two-litre bottle at most", which is the ceiling in the safety checks.
 */
