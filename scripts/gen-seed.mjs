// Generates supabase/seed.sql from the shared JSON sources of the SYNTHETIC development data (reference foods, sample workouts).
// `node scripts/gen-seed.mjs --check` fails if the committed seed is out of date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const data = JSON.parse(readFileSync('packages/shared/src/food-data.json', 'utf8'));
const wk = JSON.parse(readFileSync('packages/shared/src/workout-data.json', 'utf8'));
// Reviewed content (with provenance) or a style the database cannot store yet must not be seeded by this generator until it is extended for that content and the
// owner has approved the hosted data change and the style migration. Failing loudly beats generating a seed that silently drops the provenance.
const DB_STYLES = ['afrobeats', 'amapiano', 'hip_hop', 'latin', 'bollywood', 'low_impact'];
for (const f of data.foods)
  if (f.provenance)
    throw new Error(
      `food ${f.id} has provenance: extend scripts/gen-seed.mjs (is_synthetic, attribution) and get the hosted seed approved first`,
    );
for (const w of wk.workouts) {
  if (!DB_STYLES.includes(w.style))
    throw new Error(
      `workout ${w.id} uses style ${w.style}, which the database cannot store until the style migration is approved and applied`,
    );
  if (w.fixture)
    throw new Error(`workout ${w.id} is an internal fixture and must never be bundled or seeded`);
  if (w.draft)
    throw new Error(`workout ${w.id} is an unreviewed draft and must never be bundled or seeded`);
}
const jsonb = (v) => `${q(JSON.stringify(v))}::jsonb`;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const rows = data.foods.map(
  (f) =>
    `(${q(f.id)}, ${q(f.name)}, ${q(f.category)}, ${arr(f.regionTags)}, ${f.per100g.kcal}, ${f.per100g.proteinG}, ${f.per100g.carbsG}, ${f.per100g.fatG}, ${f.per100g.fiberG ?? 0}, ${f.servingG}, ${q(f.servingLabel)}, ${f.costTier}, ${arr(f.aliases)})`,
);
const instructorRows = wk.instructors.map(
  (i) => `(${q(i.id)}, ${q(i.displayName)}, ${q(i.bio)}, 'published', true)`,
);
const workoutRows = wk.workouts.map(
  (w) =>
    `(${q(w.id)}, ${q(w.title)}, ${q(w.style)}, ${q(w.level)}, ${q(w.intensity)}, ${q(w.impact)}, ${w.minutes}, ${q(w.summary)}, ${w.instructorId ? q(w.instructorId) : 'null'}, ${q(w.equipment)}, ${q(w.contentOrigin)}, ${jsonb(w.blocks)}, ${jsonb(w.safety)}, 'published', true)`,
);
const programRows = wk.programs.map(
  (p) =>
    `(${q(p.id)}, ${q(p.title)}, ${q(p.description)}, ${p.weeks}, ${p.sessionsPerWeek}, ${q(p.level)}, ${p.instructorId ? q(p.instructorId) : 'null'}, 'published', true)`,
);
const programWorkoutRows = wk.programs.flatMap((p) =>
  p.schedule.map((s) => `(${q(p.id)}, ${s.week}, ${s.day}, ${q(s.workoutId)})`),
);
const sql = `-- GENERATED by scripts/gen-seed.mjs from packages/shared/src/food-data.json and workout-data.json. Do not edit by hand.
-- ${data._notice}
-- ${wk._notice}
insert into public.instructors (id, display_name, bio, status, is_synthetic) values
${instructorRows.join(',\n')}
on conflict (id) do nothing;
insert into public.workouts (id, title, style, level, intensity, impact, minutes, summary, instructor_id, equipment, content_origin, blocks, safety, status, is_synthetic) values
${workoutRows.join(',\n')}
on conflict (id) do nothing;
insert into public.programs (id, title, description, weeks, sessions_per_week, level, instructor_id, status, is_synthetic) values
${programRows.join(',\n')}
on conflict (id) do nothing;
insert into public.program_workouts (program_id, week, day, workout_id) values
${programWorkoutRows.join(',\n')}
on conflict do nothing;
insert into public.foods (id, name, category, region_tags, kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g, serving_g, serving_label, cost_tier, aliases)
values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, category = excluded.category, region_tags = excluded.region_tags, kcal_100g = excluded.kcal_100g,
  protein_100g = excluded.protein_100g, carbs_100g = excluded.carbs_100g, fat_100g = excluded.fat_100g, fiber_100g = excluded.fiber_100g,
  serving_g = excluded.serving_g, serving_label = excluded.serving_label, cost_tier = excluded.cost_tier, aliases = excluded.aliases;
`;
if (process.argv.includes('--check')) {
  if (!existsSync('supabase/seed.sql') || readFileSync('supabase/seed.sql', 'utf8') !== sql) {
    console.error('supabase/seed.sql is out of date. Run: node scripts/gen-seed.mjs');
    process.exit(1);
  }
  console.log(`Seed is up to date (${data.foods.length} foods, ${wk.workouts.length} workouts).`);
} else {
  writeFileSync('supabase/seed.sql', sql);
  console.log(
    `Wrote supabase/seed.sql (${data.foods.length} foods, ${wk.workouts.length} workouts).`,
  );
}
