// Generates supabase/seed.sql from packages/shared/src/food-data.json (the single source of the synthetic reference foods).
// `node scripts/gen-food-seed.mjs --check` fails if the committed seed is out of date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const data = JSON.parse(readFileSync('packages/shared/src/food-data.json', 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const rows = data.foods.map(
  (f) =>
    `(${q(f.id)}, ${q(f.name)}, ${q(f.category)}, ${arr(f.regionTags)}, ${f.per100g.kcal}, ${f.per100g.proteinG}, ${f.per100g.carbsG}, ${f.per100g.fatG}, ${f.per100g.fiberG ?? 0}, ${f.servingG}, ${q(f.servingLabel)}, ${f.costTier}, ${arr(f.aliases)})`,
);
const sql = `-- GENERATED by scripts/gen-food-seed.mjs from packages/shared/src/food-data.json. Do not edit by hand.
-- ${data._notice}
insert into public.foods (id, name, category, region_tags, kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g, serving_g, serving_label, cost_tier, aliases)
values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, category = excluded.category, region_tags = excluded.region_tags, kcal_100g = excluded.kcal_100g,
  protein_100g = excluded.protein_100g, carbs_100g = excluded.carbs_100g, fat_100g = excluded.fat_100g, fiber_100g = excluded.fiber_100g,
  serving_g = excluded.serving_g, serving_label = excluded.serving_label, cost_tier = excluded.cost_tier, aliases = excluded.aliases;
`;
if (process.argv.includes('--check')) {
  if (!existsSync('supabase/seed.sql') || readFileSync('supabase/seed.sql', 'utf8') !== sql) {
    console.error('supabase/seed.sql is out of date. Run: node scripts/gen-food-seed.mjs');
    process.exit(1);
  }
  console.log(`Food seed is up to date (${data.foods.length} foods).`);
} else {
  writeFileSync('supabase/seed.sql', sql);
  console.log(`Wrote supabase/seed.sql (${data.foods.length} foods).`);
}
